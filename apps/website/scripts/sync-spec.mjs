// sync-spec.mjs — generates the website's spec pages from in-repo sources and
// (re)writes the docs-sync manifest (ADR-0048 §3–4).
//
// Sources (never the downstream snugprotocol/spec clone — C3):
//   - docs/spec-drafts/SPEC-1.0.md         → /docs/spec/* (split per Part + appendices)
//   - packages/protocol/schemas/*.json     → /docs/spec/schemas
//   - docs/whitepaper/dist/*.pdf           → public/whitepaper/ (served verbatim)
//
// Generated pages are VERBATIM splits — normative prose is never paraphrased here
// (lessons 2026-08-07: a derived document is checked by diffing sets and modality;
// verbatim rendering is the structural guard). Each carries a GENERATED marker.
//
// The manifest also records the AUTHORED pages' declared sources (mapping lives in
// AUTHORED_PAGES below — one home), so scripts/check-website-sync.mjs can flag any
// source drift at the root test gate.
