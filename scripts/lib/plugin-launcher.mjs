// The plugin's launcher: a POSIX sh script that finds a Node the host's PATH does not name
// (ADR-0069 §6, AC3).
//
// WHY A SCRIPT. `.mcp.json` said `command: node`, and a process a desktop host spawns gets
// no user PATH — measured 2026-09-13: `launchctl getenv PATH` is EMPTY on the owner's Mac,
// where `node` is an nvm install. So under Claude Desktop/Cowork the plugin would have
// failed to start on the very machine it was built on. The manifest now runs
// `sh ${CLAUDE_PLUGIN_ROOT}/scripts/snug` (the `args` array is passed as literal argv by
// the hosts, never through a shell, so a plugin root with a space is one argument) and the
// script looks where the installers put Node, from the SAME list the process uses to find
// `claude` (`apps/host-mcp/src/install-roots.json`) — templated here, never a second copy.
//
// WHAT IT TRUSTS. The first `node` that runs and is new enough, on PATH or under the user's
// own home: the same trust as the user's shell (threat-model residual 1). It downloads
// nothing; when there is no Node it prints one line and exits 1 — the runtime download
// (ADR-0060's pattern) is a later, pinned-and-verified step.
//
// Dependency-free node builtins only, like every other file under `scripts/`.

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The one list (see the JSON's own comment). */
export const INSTALL_ROOTS_FILE = path.join(REPO, 'apps/host-mcp/src/install-roots.json');

export function readInstallRoots(file = INSTALL_ROOTS_FILE) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** The Node major the bundle is built for (`target: node20` in the process's Vite config). */
export const NODE_MIN_MAJOR = 20;

/** `~/x` → `"$HOME/x"` (a quoted sh word); an absolute path → itself, quoted. */
function shDir(dir) {
  if (dir.startsWith('~/')) return `"$HOME/${dir.slice(2)}"`;
  return `"${dir}"`;
}

/**
 * The script text. Pure: takes the bundle's basename (it sits beside the launcher) and the
 * roots, returns sh. Every path with a variable is double-quoted; the glob in a versioned
 * root is OUTSIDE the quotes so it expands while the `$HOME` part stays one word.
 */
export function launcherScript({ bundleBasename, roots, minMajor = NODE_MIN_MAJOR }) {
  const binDirs = roots.binDirs.map(shDir).join(' ');
  const versioned = roots.versionedRoots.map(({ root, bin }) => `${shDir(root)}/*/${bin}`).join(' ');
  return `#!/bin/sh
# Snug — starts the local host process (ADR-0068 / ADR-0069).
# GENERATED by scripts/build-plugin.mjs from apps/host-mcp/src/install-roots.json — do not edit.
#
# A desktop host spawns plugin processes with no user PATH, so Node.js is looked for where
# installers put it: PATH first, then the fixed directories, then one version under each
# versioned root. The first Node that runs and is ${minMajor} or newer wins. Nothing is
# downloaded; with no Node the line below is printed and the exit code is 1.
set -u
set -f
# Builtins only: with no user PATH there may be no \`dirname\` to call.
case $0 in */*) dir=\${0%/*} ;; *) dir=. ;; esac
dir=$(cd "$dir" && pwd)
bundle="$dir/${bundleBasename}"
found=

usable() {
  [ -x "$1" ] || return 1
  v=$("$1" -p 'process.versions.node' 2>/dev/null) || return 1
  major=\${v%%.*}
  case "$major" in ''|*[!0-9]*) return 1 ;; esac
  [ "$major" -ge ${minMajor} ]
}

# 1. PATH, entry by entry (an empty entry is the working directory to a shell — skipped here).
if [ -n "\${PATH:-}" ]; then
  oldifs=$IFS
  IFS=:
  for d in $PATH; do
    IFS=$oldifs
    if [ -n "$d" ] && [ "$d" != "." ] && usable "$d/node"; then found="$d/node"; break; fi
    IFS=:
  done
  IFS=$oldifs
fi

# 2. The fixed directories.
if [ -z "$found" ] && [ -n "\${HOME:-}" ]; then
  for d in ${binDirs}; do
    if usable "$d/node"; then found="$d/node"; break; fi
  done
fi

# 3. One version under each versioned root (nvm, fnm).
if [ -z "$found" ] && [ -n "\${HOME:-}" ]; then
  set +f
  for d in ${versioned}; do
    if usable "$d/node"; then found="$d/node"; break; fi
  done
  set -f
fi

if [ -z "$found" ]; then
  printf '%s\\n' "Snug needs Node.js ${minMajor} or newer and could not find one. Install it from https://nodejs.org (on a Mac with Homebrew: brew install node), then restart your agent." >&2
  exit 1
fi

exec "$found" "$bundle" "$@"
`;
}
