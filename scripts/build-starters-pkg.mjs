#!/usr/bin/env node
// build-starters-pkg.mjs — emit the `@snugprotocol/starters` package from `examples/`
// (TASK-20260905-host-kit AC14, A3). One classic-script wrapper per starter that registers
// `{ html, meta, contract, manifest, authoring }` with the host kit's page hook, plus
// `index.json` (the pin the kit bakes in: version, the sha384 of every wrapper, the inline
// card metadata) and a `package.json`. Deterministic: sorted keys, LF, no timestamps — the
// kit's reproducibility gate builds it twice.
//
// The catalogue rule is the playground's html glob: a folder IS a starter iff it has an
// `app.html`; the optional artifacts are exactly the files the other four globs reach
// (`starter.json`, `runtime-contract.json`, `connection.json`, `authoring/{docs,prompts}/*.md`)
// and nothing deeper (ADR-0031 AC9, ADR-0035, ADR-0045 — provenance never ships).
//
// A wrapper is a SCRIPT, never markup: every `<` in the JSON is emitted as `<`, so a
// starter whose html carries `</script>` or `<!--` cannot end or escape whatever script
// element happens to load it. The publishing itself is an OWNER ACT (CLAUDE.md rule 4).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_EXAMPLES_DIR = path.join(ROOT, 'examples');
export const DEFAULT_OUT_DIR = path.join(ROOT, 'apps/host/starters-pkg');
export const STARTERS_PIN_FILE = path.join(ROOT, 'examples/starters-package.json');

export const STARTERS_INDEX_FORMAT = 'snug-starters-index/1';
export const STARTER_PAYLOAD_FORMAT = 'snug-starter/1';
export const STARTER_REGISTER_GLOBAL = '__snugStarterRegister';

/** JSON text → JS-safe text with no `<` at all (still valid JSON). Twin of the kit plugin's function. */
export function escapeForInlineScript(json) {
  return json.replace(/</g, '\\u003c');
}

const readIf = (file) => (existsSync(file) ? readFileSync(file, 'utf8') : undefined);

function readAuthoring(folderDir) {
  const out = { docs: {}, prompts: {} };
  for (const kind of ['docs', 'prompts']) {
    const dir = path.join(folderDir, 'authoring', kind);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir).sort()) {
      if (name.endsWith('.md')) out[kind][name] = readFileSync(path.join(dir, name), 'utf8');
    }
  }
  return out;
}

export function readStarter(examplesDir, folder, version) {
  const dir = path.join(examplesDir, folder);
  const html = readFileSync(path.join(dir, 'app.html'), 'utf8');
  const meta = readIf(path.join(dir, 'starter.json'));
  const contract = readIf(path.join(dir, 'runtime-contract.json'));
  const manifest = readIf(path.join(dir, 'connection.json'));
  return {
    format: STARTER_PAYLOAD_FORMAT,
    folder,
    version,
    html,
    ...(meta !== undefined ? { meta } : {}),
    ...(contract !== undefined ? { contract } : {}),
    ...(manifest !== undefined ? { manifest } : {}),
    authoring: readAuthoring(dir),
  };
}

export function wrapperSource({ name, version, payload }) {
  return [
    `/* ${name} ${version} — ${payload.folder}. Generated by scripts/build-starters-pkg.mjs from examples/${payload.folder}; do not edit. */`,
    '(function () {',
    `  var register = window.${STARTER_REGISTER_GLOBAL};`,
    "  if (typeof register !== 'function') {",
    `    throw new Error('${name}: no host registry on this page (window.${STARTER_REGISTER_GLOBAL}) — this script is loaded by the Snug host kit, not on its own');`,
    '  }',
    `  register(${escapeForInlineScript(JSON.stringify(payload))});`,
    '})();',
    '',
  ].join('\n');
}

export function starterFolders(examplesDir) {
  return readdirSync(examplesDir)
    .filter((name) => existsSync(path.join(examplesDir, name, 'app.html')))
    .sort((a, b) => a.localeCompare(b));
}

export function buildStartersPackage({ examplesDir, outDir, name, version }) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const starters = {};
  for (const folder of starterFolders(examplesDir)) {
    const payload = readStarter(examplesDir, folder, version);
    const source = wrapperSource({ name, version, payload });
    const file = `${folder}.js`;
    writeFileSync(path.join(outDir, file), source);
    const bytes = Buffer.from(source, 'utf8');
    starters[folder] = {
      file,
      sha384: createHash('sha384').update(bytes).digest('base64'),
      bytes: bytes.length,
      inline: {
        ...(payload.meta !== undefined ? { meta: payload.meta } : {}),
        ...(payload.contract !== undefined ? { contract: payload.contract } : {}),
        ...(payload.manifest !== undefined ? { manifest: payload.manifest } : {}),
      },
    };
  }
  const index = { format: STARTERS_INDEX_FORMAT, name, version, starters };
  writeFileSync(path.join(outDir, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);
  const pkg = {
    name,
    version,
    description: 'The Snug starter apps, one content-pinned script per starter — loaded on demand by the Snug host kit (https://snugprotocol.org).',
    license: 'MIT',
    homepage: 'https://snugprotocol.org',
  };
  writeFileSync(path.join(outDir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);
  writeFileSync(
    path.join(outDir, 'README.md'),
    `# ${name}\n\nThe Snug starter apps as content-pinned scripts. Each \`<starter>.js\` registers its html, docs, runtime contract and release metadata with the Snug host kit through \`window.${STARTER_REGISTER_GLOBAL}\`; \`index.json\` carries the sha384 of every file. Generated from the \`examples/\` folder of the Snug monorepo — do not edit.\n`,
  );
  return { index, files: [...Object.values(starters).map((s) => s.file), 'index.json', 'package.json', 'README.md'] };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outFlag = process.argv.find((a) => a.startsWith('--out='));
  const outDir = outFlag === undefined ? DEFAULT_OUT_DIR : path.resolve(outFlag.slice('--out='.length));
  const pin = JSON.parse(readFileSync(STARTERS_PIN_FILE, 'utf8'));
  const { index } = buildStartersPackage({ examplesDir: DEFAULT_EXAMPLES_DIR, outDir, name: pin.name, version: pin.version });
  console.log(`build-starters-pkg: ${pin.name}@${pin.version} — ${Object.keys(index.starters).length} starters → ${path.relative(ROOT, outDir)}`);
}
